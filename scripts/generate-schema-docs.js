import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const repoRoot = path.resolve(__dirname, '..');
const prismaSchemaPath = path.join(repoRoot, 'backend', 'schema.prisma');
const outputDocPath = path.join(repoRoot, 'docs', 'DATABASE_SCHEMA.md');

function parsePrismaSchema(schemaContent) {
  const lines = schemaContent.split('\n');
  const models = [];
  let currentModel = null;

  for (let rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith('//') || line.startsWith('datasource') || line.startsWith('generator')) {
      continue;
    }

    if (line.startsWith('model ')) {
      const parts = line.split(/\s+/);
      currentModel = {
        name: parts[1].replace('{', '').trim(),
        fields: [],
        indexes: []
      };
      models.push(currentModel);
      continue;
    }

    if (currentModel && line === '}') {
      currentModel = null;
      continue;
    }

    if (currentModel) {
      if (line.startsWith('@@')) {
        currentModel.indexes.push(line);
        continue;
      }

      // Parse field line: fieldName FieldType attributes // comments
      const commentIndex = line.indexOf('//');
      let comment = '';
      let fieldDef = line;
      if (commentIndex !== -1) {
        comment = line.substring(commentIndex + 2).trim();
        fieldDef = line.substring(0, commentIndex).trim();
      }

      const tokens = fieldDef.split(/\s+/);
      if (tokens.length >= 2) {
        const name = tokens[0];
        const type = tokens[1];
        const attributes = tokens.slice(2).join(' ');
        currentModel.fields.push({ name, type, attributes, comment });
      }
    }
  }

  return models;
}

function generateMermaidDiagram(models) {
  const modelNames = new Set(models.map(m => m.name));
  const relationships = [];

  for (const model of models) {
    for (const field of model.fields) {
      const cleanType = field.type.replace('[]', '').replace('?', '');
      if (modelNames.has(cleanType)) {
        const isArray = field.type.includes('[]');
        const isOptional = field.type.includes('?');

        if (isArray) {
          // 1-to-many: model ||--o{ cleanType
          relationships.push(`  ${model.name} ||--o{ ${cleanType} : "${field.name}"`);
        } else if (isOptional) {
          relationships.push(`  ${model.name} }o--o| ${cleanType} : "${field.name}"`);
        } else {
          relationships.push(`  ${model.name} }o--|| ${cleanType} : "${field.name}"`);
        }
      }
    }
  }

  // Deduplicate relationships for cleaner diagram
  const uniqueRelations = Array.from(new Set(relationships));

  let diagram = '```mermaid\nerDiagram\n';
  diagram += uniqueRelations.join('\n') + '\n```';
  return diagram;
}

function generateMarkdown(models) {
  let md = `# Syncly Database Schema Reference\n\n`;
  md += `> [!NOTE]\n`;
  md += `> This documentation is automatically generated from [\`backend/schema.prisma\`](../backend/schema.prisma).\n`;
  md += `> Do not edit this file manually. It is kept in sync by the daily maintenance workflow.\n\n`;

  md += `## Entity-Relationship Diagram\n\n`;
  md += generateMermaidDiagram(models) + `\n\n`;

  md += `## Data Models\n\n`;

  for (const model of models) {
    md += `### \`${model.name}\`\n\n`;
    md += `| Field | Type | Attributes | Notes |\n`;
    md += `| :--- | :--- | :--- | :--- |\n`;

    for (const field of model.fields) {
      const attributes = field.attributes ? `\`${field.attributes}\`` : '-';
      const notes = field.comment || '-';
      md += `| \`${field.name}\` | \`${field.type}\` | ${attributes} | ${notes} |\n`;
    }

    if (model.indexes.length > 0) {
      md += `\n**Indexes / Constraints:**\n`;
      for (const idx of model.indexes) {
        md += `- \`${idx}\`\n`;
      }
    }

    md += `\n`;
  }

  return md;
}

function run() {
  if (!fs.existsSync(prismaSchemaPath)) {
    console.error(`Error: Prisma schema not found at ${prismaSchemaPath}`);
    process.exit(1);
  }

  const schemaContent = fs.readFileSync(prismaSchemaPath, 'utf8');
  const models = parsePrismaSchema(schemaContent);
  const markdown = generateMarkdown(models);

  const docsDir = path.dirname(outputDocPath);
  if (!fs.existsSync(docsDir)) {
    fs.mkdirSync(docsDir, { recursive: true });
  }

  fs.writeFileSync(outputDocPath, markdown, 'utf8');
  console.log(`Successfully generated schema documentation at: ${outputDocPath}`);
}

run();
